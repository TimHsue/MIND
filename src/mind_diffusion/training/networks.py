# Timestep embedding used in the DDPM++ and ADM architectures.

@persistence.persistent_class
class PositionalEmbedding(torch.nn.Module):
    def __init__(self, num_channels, max_positions=10000, endpoint=False):
        super().__init__()
        self.num_channels = num_channels
        self.max_positions = max_positions
        self.endpoint = endpoint

    def forward(self, x):
        freqs = torch.arange(start=0, end=self.num_channels//2, dtype=torch.float32, device=x.device)
        freqs = freqs / (self.num_channels // 2 - (1 if self.endpoint else 0))
        freqs = (1 / self.max_positions) ** freqs
        x = x.ger(freqs.to(x.dtype))
        x = torch.cat([x.cos(), x.sin()], dim=1)
        return x

#----------------------------------------------------------------------------
# Timestep embedding used in the NCSN++ architecture.

@persistence.persistent_class
class LabelFourierEmbedding(torch.nn.Module):
    def __init__(self, num_channels, label_dim, scale=32):
        super().__init__()
        self.register_buffer('freqs', torch.randn(num_channels) * scale)  # Remove register_buffer for simplicity
        self.out = torch.nn.Linear(label_dim * num_channels * 2, num_channels)

    def forward(self, x):
        # x: [batch_size, label_dim]
        batch_size = x.shape[0]
        freqs = self.freqs  # [num_channels // 2]
        x = x.unsqueeze(2)  # [batch_size, label_dim, 1]
        freqs = freqs.unsqueeze(0).unsqueeze(0)  # [1, 1, num_channels // 2]
        x = x * (2 * np.pi * freqs)  # Element-wise multiplication
        x = torch.cat([x.cos(), x.sin()], dim=2)  # [batch_size, label_dim, num_channels]
        x = x.view(batch_size, -1)  # Flatten to [batch_size, label_dim * num_channels]
        x = self.out(x)  # Final linear layer
        return x

#----------------------------------------------------------------------------
# MIND conditional backbone, adapted from the EDM DDPM++ implementation.
# Architecture background: "Score-Based Generative Modeling through
# Stochastic Differential Equations" (Song et al.).
# https://github.com/yang-song/score_sde_pytorch
@persistence.persistent_class
class MINDUNet(torch.nn.Module):
    def __init__(self,
        img_resolution,                     # Image resolution at input/output.
        in_channels,                        # Number of color channels at input.
        out_channels,                       # Number of color channels at output.
        label_dim           = 0,            # Number of class labels, 0 = unconditional.

        model_channels      = 192,          # Base multiplier for the number of channels.
        channel_mult        = [2,2,3,4,2],    # Per-resolution multipliers for the number of channels.
        channel_mult_emb    = 4,            # Multiplier for the dimensionality of the embedding vector.
        num_blocks          = 4,            # Number of residual blocks per resolution.
        attn_resolutions    = [16, 8],      # List of resolutions with self-attention.
        dropout             = 0.0,         # Dropout probability of intermediate activations.
        label_dropout       = 0.10,         # Classifier-free training dropout of the released MIND model.
        label_scale         = [10,10,10],  # Label embedding scale for each resolution.

        channel_mult_noise  = 1,            # Timestep embedding size: 1 for DDPM++, 2 for NCSN++.
        resample_filter     = [1,1],        # Resampling filter: [1,1] for DDPM++, [1,3,3,1] for NCSN++.
    ):
        assert label_dim == len(label_scale)

        super().__init__()
        self.label_dropout = label_dropout
        emb_channels = model_channels * channel_mult_emb
        noise_channels = model_channels * channel_mult_noise
        init = dict(init_mode='xavier_uniform')
        init_zero = dict(init_mode='xavier_uniform', init_weight=1e-5)
        init_attn = dict(init_mode='xavier_uniform', init_weight=np.sqrt(0.2))
        block_kwargs = dict(
            emb_channels=emb_channels, num_heads=1, dropout=dropout, skip_scale=np.sqrt(0.5), eps=1e-6,
            resample_filter=resample_filter, resample_proj=True, adaptive_scale=False,
            init=init, init_zero=init_zero, init_attn=init_attn,
        )

        # Mapping.
        self.map_noise = PositionalEmbedding(num_channels=noise_channels, endpoint=True)

        self.map_labels = torch.nn.ModuleList([
            LabelFourierEmbedding(label_dim=1, num_channels=noise_channels, scale=label_scale[i]) for i in range(len(label_scale))
        ])

        self.label_emb = Linear(in_features=noise_channels * label_dim, out_features=noise_channels, **init) if label_dim else None


        total_embedding_dim = noise_channels

        if len(self.map_labels) > 0:
            total_embedding_dim += noise_channels


        self.map_layer0 = Linear(in_features=total_embedding_dim, out_features=emb_channels, **init)
        self.map_layer1 = Linear(in_features=emb_channels, out_features=emb_channels, **init)

        # Encoder.
        self.enc = torch.nn.ModuleDict()
        cout = in_channels
        caux = in_channels
        for level, mult in enumerate(channel_mult):
            res = img_resolution >> level
            if level == 0:
                cin = cout
                cout = model_channels
                self.enc[f'{res}x{res}_conv'] = Conv2d(in_channels=cin, out_channels=cout, kernel=3, **init)
            else:
                self.enc[f'{res}x{res}_down'] = UNetBlock(in_channels=cout, out_channels=cout, down=True, **block_kwargs)
                self.enc[f'{res}x{res}_aux_down'] = Conv2d(in_channels=caux, out_channels=caux, kernel=0, down=True, resample_filter=resample_filter)
                self.enc[f'{res}x{res}_aux_skip'] = Conv2d(in_channels=caux, out_channels=cout, kernel=1, **init)
            for idx in range(num_blocks):
                cin = cout
                cout = model_channels * mult
                attn = (res in attn_resolutions)
                self.enc[f'{res}x{res}_block{idx}'] = UNetBlock(in_channels=cin, out_channels=cout, attention=attn, **block_kwargs)
        skips = [block.out_channels for name, block in self.enc.items() if 'aux' not in name]

        # Decoder.
        self.dec = torch.nn.ModuleDict()
        for level, mult in reversed(list(enumerate(channel_mult))):
            res = img_resolution >> level
            if level == len(channel_mult) - 1:
                self.dec[f'{res}x{res}_in0'] = UNetBlock(in_channels=cout, out_channels=cout, attention=True, **block_kwargs)
                self.dec[f'{res}x{res}_in1'] = UNetBlock(in_channels=cout, out_channels=cout, **block_kwargs)
            else:
                self.dec[f'{res}x{res}_up'] = UNetBlock(in_channels=cout, out_channels=cout, up=True, **block_kwargs)
            for idx in range(num_blocks + 1):
                cin = cout + skips.pop()
                cout = model_channels * mult
                attn = (idx == num_blocks and res in attn_resolutions)
                self.dec[f'{res}x{res}_block{idx}'] = UNetBlock(in_channels=cin, out_channels=cout, attention=attn, **block_kwargs)
            if level < len(channel_mult) - 1:
                self.dec[f'{res}x{res}_aux_up'] = Conv2d(in_channels=out_channels, out_channels=out_channels, kernel=0, up=True, resample_filter=resample_filter)
            self.dec[f'{res}x{res}_aux_norm'] = GroupNorm(num_channels=cout, eps=1e-6)
            self.dec[f'{res}x{res}_aux_conv'] = Conv2d(in_channels=cout, out_channels=out_channels, kernel=3, **init_zero)

    def forward(self, x, noise_labels, class_labels, drop_mask=None):
        # Mapping.
        emb_noise = self.map_noise(noise_labels)
        emb_noise = emb_noise.reshape(emb_noise.shape[0], 2, -1).flip(1).reshape(*emb_noise.shape) # swap sin/cos

        embeddings = [emb_noise]

        if len(self.map_labels) > 0:
            label_embeddings = torch.stack([map_label(class_labels[:, i:i+1]) for i, map_label in enumerate(self.map_labels)], dim=1)  # Shape: (batch_size, label_dim, noise_channels)
            # swap sin/cos
            label_embeddings = label_embeddings.reshape(label_embeddings.shape[0], label_embeddings.shape[1], 2, -1).flip(2).reshape(*label_embeddings.shape)

            if self.training and self.label_dropout:

                save_indices_train_drop = (torch.rand([class_labels.shape[0], 1, 1], device=class_labels.device) >= self.label_dropout).to(label_embeddings.dtype)
                label_embeddings = label_embeddings * save_indices_train_drop


            if drop_mask is not None:
                label_embeddings = label_embeddings * drop_mask.to(label_embeddings.dtype)

            label_embeddings = label_embeddings.reshape(label_embeddings.shape[0], -1)  # Shape: (batch_size, label_dim * noise_channels)

            emb_label = self.label_emb(label_embeddings) * np.sqrt(len(self.map_labels))
            embeddings.append(emb_label)


        emb = torch.cat(embeddings, dim=1)
        emb = silu(self.map_layer0(emb))
        emb = silu(self.map_layer1(emb))

        # Encoder.
        skips = []
        aux = x
        for name, block in self.enc.items():
            if 'aux_down' in name:
                aux = block(aux)
            elif 'aux_skip' in name:
                x = skips[-1] = x + block(aux)
            else:
                x = block(x, emb) if isinstance(block, UNetBlock) else block(x)
                skips.append(x)

        # Decoder.
        aux = None
        tmp = None
        for name, block in self.dec.items():
            if 'aux_up' in name:
                aux = block(aux)
            elif 'aux_norm' in name:
                tmp = block(x)
            elif 'aux_conv' in name:
                tmp = block(silu(tmp))
                aux = tmp if aux is None else tmp + aux
            else:
                if x.shape[1] != block.in_channels:
                    x = torch.cat([x, skips.pop()], dim=1)
                x = block(x, emb)
        return aux


